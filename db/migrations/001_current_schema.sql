
-- Name: audit_current_user_id(); Type: FUNCTION; Schema: public; Owner: -

CREATE FUNCTION public.audit_current_user_id() RETURNS integer
    LANGUAGE plpgsql
    AS $$
DECLARE
    raw_value text;
BEGIN
    raw_value := current_setting('app.current_user_id', true);

    IF raw_value IS NULL OR BTRIM(raw_value) = '' THEN
        RETURN NULL;
    END IF;

    RETURN raw_value::integer;
EXCEPTION
    WHEN OTHERS THEN
        RETURN NULL;
END;
$$;


-- Name: set_update_metadata(); Type: FUNCTION; Schema: public; Owner: -

CREATE FUNCTION public.set_update_metadata() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    NEW.date_update = NOW();

    IF current_setting('app.current_user_id', true) IS NOT NULL
        AND current_setting('app.current_user_id', true) <> ''
    THEN
        NEW.user_update = current_setting('app.current_user_id', true)::integer;
    END IF;

    RETURN NEW;
END;
$$;


-- Name: write_crud_audit(); Type: FUNCTION; Schema: public; Owner: -

CREATE FUNCTION public.write_crud_audit() RETURNS trigger
    LANGUAGE plpgsql
    AS $_$
DECLARE
    source_row jsonb;
    record_pk jsonb := '{}'::jsonb;
    pk_name text;
    changed_by_user_id integer;
BEGIN
    source_row := CASE
        WHEN TG_OP = 'DELETE' THEN to_jsonb(OLD)
        ELSE to_jsonb(NEW)
    END;

    changed_by_user_id := public.audit_current_user_id();

    FOREACH pk_name IN ARRAY TG_ARGV LOOP
        record_pk := record_pk || jsonb_build_object(pk_name, source_row -> pk_name);
    END LOOP;

    EXECUTE format(
        'INSERT INTO public.%I_l (operation, changed_at, changed_by_user_id, record_pk, row_data)
         VALUES ($1, NOW(), $2, $3, $4)',
        TG_TABLE_NAME
    )
    USING TG_OP, changed_by_user_id, record_pk, source_row;

    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;

    RETURN NEW;
END;
$_$;


-- Name: write_survey_auto_creation_config_audit(); Type: FUNCTION; Schema: public; Owner: -

CREATE FUNCTION public.write_survey_auto_creation_config_audit() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
DECLARE
    changed_by integer;
    audit_record_pk jsonb;
    audit_row_data jsonb;
BEGIN
    IF current_setting('app.current_user_id', true) IS NOT NULL
        AND current_setting('app.current_user_id', true) <> ''
    THEN
        changed_by := current_setting('app.current_user_id', true)::integer;
    END IF;

    IF TG_OP = 'DELETE' THEN
        audit_record_pk := jsonb_build_object('id_config', OLD.id_config, 'id_survey', OLD.id_survey);
        audit_row_data := to_jsonb(OLD);
    ELSE
        audit_record_pk := jsonb_build_object('id_config', NEW.id_config, 'id_survey', NEW.id_survey);
        audit_row_data := to_jsonb(NEW);
    END IF;

    INSERT INTO public.survey_auto_creation_config_l
    (
        operation,
        changed_by_user_id,
        record_pk,
        row_data
    )
    VALUES
    (
        TG_OP,
        changed_by,
        audit_record_pk,
        audit_row_data
    );

    RETURN COALESCE(NEW, OLD);
END;
$$;




