-- Name: survey_schedule; Type: VIEW; Schema: public; Owner: -

CREATE VIEW public.survey_schedule AS
 SELECT s.id_survey,
    min(os.date_begin) AS date_begin,
    max(os.date_end) AS date_end
   FROM (public.survey s
     LEFT JOIN public.organization_survey os ON ((os.id_survey = s.id_survey)))
  GROUP BY s.id_survey;


