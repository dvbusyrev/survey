CREATE TABLE IF NOT EXISTS public.survey_template (
    id_survey_template integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name_survey_template text NOT NULL,
    description text,
    date_begin date NOT NULL,
    date_end date NOT NULL,
    CONSTRAINT survey_template_date_range_check CHECK (date_end > date_begin)
);

CREATE TABLE IF NOT EXISTS public.survey_template_question (
    id_survey_template_question integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_survey_template integer NOT NULL,
    question_order integer NOT NULL,
    question_text text NOT NULL,
    CONSTRAINT survey_template_question_template_order_key
        UNIQUE (id_survey_template, question_order),
    CONSTRAINT survey_template_question_id_survey_template_fkey
        FOREIGN KEY (id_survey_template)
        REFERENCES public.survey_template(id_survey_template)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.organization_survey_template (
    id_organization_survey_template integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_organization integer NOT NULL,
    id_survey_template integer NOT NULL,
    CONSTRAINT organization_survey_template_organization_template_key
        UNIQUE (id_organization, id_survey_template),
    CONSTRAINT organization_survey_template_id_organization_fkey
        FOREIGN KEY (id_organization)
        REFERENCES public.organization(id_organization)
        ON DELETE RESTRICT,
    CONSTRAINT organization_survey_template_id_survey_template_fkey
        FOREIGN KEY (id_survey_template)
        REFERENCES public.survey_template(id_survey_template)
        ON DELETE CASCADE
);

