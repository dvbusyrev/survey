INSERT INTO public.survey_template (
    id_survey_template,
    name_survey_template,
    description,
    date_begin,
    date_end
)
SELECT
    survey.id_survey,
    survey.name_survey,
    survey.description,
    survey.date_begin,
    survey.date_end
FROM public.survey survey
INNER JOIN migrated_survey_templates template
    ON template.id_survey = survey.id_survey
ON CONFLICT (id_survey_template) DO UPDATE
SET
    name_survey_template = EXCLUDED.name_survey_template,
    description = EXCLUDED.description,
    date_begin = EXCLUDED.date_begin,
    date_end = EXCLUDED.date_end;

