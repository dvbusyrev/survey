    question.id_question,
    question.id_survey,
    question.question_order,
    question.question_text
FROM public.survey_question question
INNER JOIN migrated_survey_templates template
    ON template.id_survey = question.id_survey
ON CONFLICT (id_survey_template_question) DO UPDATE
SET
    id_survey_template = EXCLUDED.id_survey_template,
    question_order = EXCLUDED.question_order,
    question_text = EXCLUDED.question_text;

